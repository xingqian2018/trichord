#!/usr/bin/env python3
"""Per-validation-set tables (all six sets + six-set mean, doc-isolated and packed) for the progress reports in reports_xx/.

Reads Boxiang's ladder working copy:
  doc-isolated  results/<Change ID>/ckpts/<rung>/eval/RESULTS.md (column "doc-isolated")
  packed        results/<Change ID>/scores.json (rungs.<rung>.val); finals not filed yet are read from the run log
                (<RUNS>/<run>/logs/*.log, "validation-<set> loss at iteration N on validation set") and marked †
and rewrites the block between <!-- settables:begin --> and <!-- settables:end --> of each report given.

    python3 reports_xx/gen_tables.py reports_xx/qwen3_scaling_ladder_progress.md:zh reports_xx/qwen3_scaling_ladder_progress_en.md:en
"""
import glob
import json
import os
import re
import sys

LADDER = "/scratch/fsw/portfolios/cosmos/projects/cosmos_base_training/cosmos_llm_scaling_ladder"
RUNS = "/scratch/fsw/portfolios/cosmos/projects/cosmos_base_training/users/boxiangw/runs/scaling_ladder/qwen3_tpp200"
RUNGS = ["q0", "q1", "q2", "q3", "q4", "q5"]
SETS = ["val_v2_decon", "uncheatable_decon", "codefresh_decon", "v3small_decon", "pile_test_decon", "pile_10k_decon"]
# Change ID -> experiment name of its runs (<exp>-<rung>-tpp200-s1)
ARMS = [("BASE", "qwen3_tpp200_v1"), ("OPT_MUON", "qwen3_tpp200_muon"), ("OPT_MUONH", "qwen3_tpp200_muonh"),
        ("KD_MUONH_A0P7", "qwen3_tpp200_muonh_kd_a0p7"), ("KD_MUONH_A0P8", "qwen3_tpp200_muonh_kd_a0p8"),
        ("KD_MUONH_A0P9", "qwen3_tpp200_muonh_kd_a0p9")]
FINAL = re.compile(r"validation-(\S+) loss at iteration (\d+) on validation set \| lm loss value: ([0-9.Ee+-]+)")

TEXT = {
    "zh": {"doc": "doc-isolated", "packed": "packed", "mean": "六集平均",
           "intro": "每个格子是 loss，括号内为相对 BASE 的 dCE（负数更好）；· = 还没有结果；† = Boxiang 还没归档，取自 run log。"
                    "本节由 `reports_xx/gen_tables.py` 自动生成，不要手改。"},
    "en": {"doc": "doc-isolated", "packed": "packed", "mean": "six-set mean",
           "intro": "Each cell is the loss with the dCE vs BASE in parentheses (negative is better); · = no result yet; † = not filed by "
                    "Boxiang yet, read from the run log. This section is generated by `reports_xx/gen_tables.py`; do not edit by hand."},
}


def doc_results():
    out = {}
    for change, _ in ARMS:
        for q in RUNGS:
            p = f"{LADDER}/results/{change}/ckpts/{q}/eval/RESULTS.md"
            if not os.path.isfile(p):
                continue
            vals = {}
            for line in open(p):
                parts = [x.strip() for x in line.split("|")]
                if len(parts) > 4 and parts[1] in SETS:
                    vals[parts[1]] = float(parts[4])
            if len(vals) == len(SETS):
                out[(change, q)] = (vals, False)
    return out


def log_final(run):
    vals, it = {}, -1
    for f in sorted(glob.glob(f"{RUNS}/{run}/logs/*.log")):
        for m in FINAL.finditer(open(f, errors="replace").read()):
            n = int(m.group(2))
            if n > it:
                vals, it = {}, n
            if n == it:
                vals[m.group(1)] = float(m.group(3))
    return vals if all(s in vals for s in SETS) else None


def packed_results():
    out = {}
    for change, exp in ARMS:
        p = f"{LADDER}/results/{change}/scores.json"
        rungs = json.load(open(p)).get("rungs", {}) if os.path.isfile(p) else {}
        for q in RUNGS:
            v = (rungs.get(q) or {}).get("val") or {}
            if all(s in v for s in SETS):
                out[(change, q)] = ({s: v[s] for s in SETS}, False)
                continue
            if (rungs.get(q) or {}).get("status") in ("paused", "stopped"):
                continue
            v = log_final(f"{exp}-{q}-tpp200-s1")
            if v:
                out[(change, q)] = (v, True)
    return out


def table(res, key, title):
    rows = [f"**{title}**", "", "| arm | " + " | ".join(RUNGS) + " |", "|---|" + "---|" * len(RUNGS)]
    get = (lambda v: sum(v[s] for s in SETS) / len(SETS)) if key == "mean" else (lambda v: v[key])
    for change, _ in ARMS:
        cells = []
        for q in RUNGS:
            if (change, q) not in res:
                cells.append("·")
                continue
            vals, unfiled = res[(change, q)]
            x = get(vals)
            cell = f"{x:.4f}"
            if change != "BASE" and ("BASE", q) in res:
                d = x - get(res[("BASE", q)][0])
                cell += f" ({'−' if d < 0 else '+'}{abs(d):.3f})"
            cells.append(cell + ("†" if unfiled else ""))
        rows.append(f"| {change} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def block(lang):
    t = TEXT[lang]
    parts = [t["intro"], ""]
    for proto, res in (("doc", doc_results()), ("packed", packed_results())):
        for key in SETS + ["mean"]:
            name = t["mean"] if key == "mean" else key
            parts += [table(res, key, f"{name} — {t[proto]}"), ""]
    return "\n".join(parts).rstrip()


def main():
    for spec in sys.argv[1:]:
        path, lang = spec.rsplit(":", 1)
        s = open(path).read()
        new, n = re.subn(r"(<!-- settables:begin -->\n).*?(<!-- settables:end -->)",
                         lambda m: m.group(1) + block(lang) + "\n" + m.group(2), s, flags=re.S)
        if n != 1:
            sys.exit(f"{path}: expected one settables block, found {n}")
        open(path, "w").write(new)
        print(f"updated {path}")


if __name__ == "__main__":
    main()
